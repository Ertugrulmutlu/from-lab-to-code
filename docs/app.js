function svg(name,cls='') {
  return name==='github'
    ? `<svg class="${cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${ICONS.github}</svg>`
    : `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]||ICONS.image}</svg>`;
}
function escapeHTML(value) {
  return String(value??'').replace(/[&<>"']/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
}
function safeURL(value) {
  try {
    if(!value) return '';
    const url=new URL(value);
    return url.protocol==='https:' ? escapeHTML(url.href) : '';
  } catch {return '';}
}
function action(text,url,icon,style='') {
  const href=safeURL(url);
  const inner=`${svg(icon,'action-icon')}<span>${escapeHTML(text)}</span>${style.includes('button')?'<span class="arrow" aria-hidden="true">→</span>':''}`;
  return href
    ? `<a class="action-link ${style}" href="${href}" target="_blank" rel="noopener noreferrer">${inner}</a>`
    : `<span class="action-link action-disabled ${style}" aria-label="${escapeHTML(text)}: coming soon" title="Coming soon">${inner}</span>`;
}
function renderFeatured() {
  const project=PROJECTS.find(p=>p.featured&&p.status==='published') || PROJECTS.find(p=>p.status==='published');
  if(!project) { $('featured').hidden=true; return; }
  $('featured-title').textContent=`Project #${project.id} — ${project.title}`;
  $('featured-subtitle').textContent=project.short;
  $('featured-description').textContent=project.description;
  $('featured-actions').innerHTML=action('View Project',project.githubUrl,'github','button button-blue')+action('Read Article',project.articleUrl,'document','button button-outline');
  // Built-in images belong only to Project #01. New featured projects can
  // provide previewImages: ['assets/example-1.jpg', ...] after publishing.
  const labels=project.previewSteps||['Discover','Implement','Visualize','Explain'];
  const previews=Array.isArray(project.previewImages)?project.previewImages:[];
  const panels=labels.map((label,i)=>{
    const imagePath=previews[i];
    const safePath=typeof imagePath==='string' && /^(assets\/[a-zA-Z0-9_./-]+|https:\/\/[a-zA-Z0-9._/-]+)$/.test(imagePath) ? imagePath : '';
    const imageClass=safePath ? 'feature-image-media' : (project.builtInPreview ? `feature-image-${i%4}` : 'feature-image-placeholder');
    const background=safePath ? ` style=\"background-image:url('${safePath}')\"` : '';
    return `<div class=\"feature-step\"><div class=\"feature-image ${imageClass}\" role=\"img\" aria-label=\"Preview: ${escapeHTML(label)}\"${background}></div><span class=\"feature-caption\">${escapeHTML(label)}</span></div>`;
  });
  $('featured-visual').innerHTML=`<div class=\"feature-steps\">${panels.join('<span class=\"step-arrow\" aria-hidden=\"true\">→</span>')}</div>`;
}
function renderFilters() {
  const categories=CATEGORY_ORDER.filter(cat=>cat==='All'||PROJECTS.some(p=>p.category===cat));
  $('category-filters').innerHTML=categories.map(category=>`<button type="button" class="filter-chip ${category===activeCategory?'is-active':''}" data-category="${escapeHTML(category)}" aria-pressed="${category===activeCategory}">${escapeHTML(category)}</button>`).join('');
  $('category-filters').querySelectorAll('button').forEach(button=>button.addEventListener('click',()=>{activeCategory=button.dataset.category;renderFilters();renderProjects();}));
}
function cardMarkup(project) {
  const planned=project.status!=='published';
  return `<article class="project-card ${planned?'is-planned':'is-published'}" style="--card-accent:var(--accent-${escapeHTML(project.accent||'cyan')})">
    <div class="project-symbol">${svg(project.icon,'project-symbol-icon')}</div>
    <div class="project-body">
      <div class="project-eyebrow"><span class="project-number">${escapeHTML(project.id)}</span><span class="project-status ${planned?'status-planned':'status-live'}">${planned?'COMING SOON':'PUBLISHED'}</span></div>
      <h3 title="${escapeHTML(project.title)}">${escapeHTML(project.title)}</h3>
      <p title="${escapeHTML(project.short)}">${escapeHTML(project.short)}</p>
      <div class="card-links">${action('Project',project.githubUrl,'github')}${action('Article',project.articleUrl,'document')}</div>
    </div></article>`;
}
function renderProjects() {
  const visible=activeCategory==='All'?PROJECTS:PROJECTS.filter(p=>p.category===activeCategory);
  const live=PROJECTS.filter(p=>p.status==='published').length;
  const planned=PROJECTS.length-live;
  $('project-count').innerHTML=`<span class="count-mark" aria-hidden="true">▱</span><strong>${live} published</strong><span class="count-dot">·</span>${planned} planned`;
  $('project-grid').innerHTML=visible.length?visible.map(cardMarkup).join(''):'<p class="empty-state">No projects in this category yet.</p>';
}
